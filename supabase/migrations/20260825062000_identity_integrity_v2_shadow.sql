create or replace function public.admin_set_identity_rollout_v1(
  p_public_identity boolean,
  p_signup_handle boolean,
  p_public_profiles boolean,
  p_identity_cards boolean,
  p_creator_verification boolean,
  p_research_submission boolean,
  p_confirmation text default null,
  p_reason text default null
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
begin
  if not public.echo_is_admin() then
    raise exception 'admin_aal2_required' using errcode='42501';
  end if;
  if (coalesce(p_signup_handle,false) or coalesce(p_public_profiles,false) or coalesce(p_identity_cards,false)
      or coalesce(p_creator_verification,false) or coalesce(p_research_submission,false))
     and not coalesce(p_public_identity,false) then
    raise exception 'identity_rollout_master_required' using errcode='22023';
  end if;
  if (coalesce(p_public_identity,false) or coalesce(p_signup_handle,false) or coalesce(p_public_profiles,false)
      or coalesce(p_identity_cards,false) or coalesce(p_creator_verification,false) or coalesce(p_research_submission,false))
     and coalesce(p_confirmation,'') <> 'ENABLE_IDENTITY_V2' then
    raise exception 'identity_rollout_confirmation_required' using errcode='42501';
  end if;
  if p_reason is not null and char_length(p_reason)>1000 then
    raise exception 'identity_rollout_reason_too_long' using errcode='22023';
  end if;

  update public.echo_identity_rollout_settings
  set public_identity_enabled=coalesce(p_public_identity,false),
      signup_handle_enabled=coalesce(p_signup_handle,false),
      public_profiles_enabled=coalesce(p_public_profiles,false),
      identity_cards_enabled=coalesce(p_identity_cards,false),
      creator_verification_enabled=coalesce(p_creator_verification,false),
      research_submission_enabled=coalesce(p_research_submission,false),
      updated_by=auth.uid(),
      last_change_reason=nullif(btrim(coalesce(p_reason,'')),''),
      updated_at=now()
  where singleton=true;

  return public.echo_identity_rollout_status_v1();
end;
$$;
revoke all on function public.admin_set_identity_rollout_v1(boolean,boolean,boolean,boolean,boolean,boolean,text,text) from public,anon;
grant execute on function public.admin_set_identity_rollout_v1(boolean,boolean,boolean,boolean,boolean,boolean,text,text) to authenticated;

