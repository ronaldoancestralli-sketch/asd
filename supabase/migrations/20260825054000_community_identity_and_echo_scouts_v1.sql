create or replace function public.echo_recompute_community_reputation(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path=''
as $$
declare
  v_verified integer;
  v_corroborated integer;
  v_first integer;
  v_decided integer;
  v_accepted integer;
  v_points integer;
  v_rate numeric(5,4);
  v_tier text;
begin
  select
    count(*) filter(where status='verified')::integer,
    count(*) filter(where status='corroborated')::integer,
    count(*) filter(where status='verified' and is_first_discovery=true)::integer,
    count(*) filter(where status in ('verified','corroborated','rejected','contested'))::integer
  into v_verified,v_corroborated,v_first,v_decided
  from public.echo_research_contributions
  where contributor_id=p_user_id;

  v_verified:=coalesce(v_verified,0); v_corroborated:=coalesce(v_corroborated,0); v_first:=coalesce(v_first,0); v_decided:=coalesce(v_decided,0);
  v_accepted:=v_verified+v_corroborated;
  v_points:=v_verified*10+v_corroborated*4+v_first*15;
  v_rate:=case when v_decided=0 then 0 else least(1,greatest(0,v_accepted::numeric/v_decided::numeric)) end;
  v_tier:=case
    when v_points>=8000 and v_verified>=400 and v_first>=10 then 'arena_legend'
    when v_points>=2500 and v_verified>=150 then 'vanguard'
    when v_points>=900 and v_verified>=60 then 'analyst'
    when v_points>=350 and v_verified>=25 then 'cartographer'
    when v_points>=120 and v_verified>=10 then 'tracker'
    when v_points>=30 and v_verified>=3 then 'echo_scout'
    else 'member'
  end;

  insert into public.echo_community_reputation(user_id,reputation_points,community_tier,verified_count,corroborated_count,first_discoveries,acceptance_rate,updated_at)
  values(p_user_id,v_points,v_tier,v_verified,v_corroborated,v_first,v_rate,now())
  on conflict(user_id) do update set
    reputation_points=excluded.reputation_points,community_tier=excluded.community_tier,
    verified_count=excluded.verified_count,corroborated_count=excluded.corroborated_count,
    first_discoveries=excluded.first_discoveries,acceptance_rate=excluded.acceptance_rate,updated_at=now();
end;
$$;
revoke all on function public.echo_recompute_community_reputation(uuid) from public, anon, authenticated, service_role;

