-- Um histórico aceito sem revisor identificável não pode ser convertido em
-- reputação por inferência. A implantação para e exige reconciliação humana.
do $$
begin
  if exists(
    select 1 from public.echo_research_contributions c
    where c.status in ('corroborated','verified','rejected','contested') and c.reviewed_by is null
  ) then
    raise exception 'research_review_actor_missing_requires_reconciliation' using errcode='23514';
  end if;
end $$;

-- Backfill fail-closed: decisões existentes ganham evento gênese, mas nenhuma
-- recebe reputação até uma confirmação independente posterior.
do $$
declare
  r record;
  v_note_hash text;
  v_event_hash text;
  v_event_id bigint;
  v_state text;
begin
  for r in
    select c.*
    from public.echo_research_contributions c
    where c.status<>'pending'
    order by coalesce(c.reviewed_at,c.updated_at,c.submitted_at),c.id
  loop
    if r.reviewed_by is null then
      if r.status='superseded' then
        update public.echo_research_contributions
        set review_confirmation_state='not_applicable'
        where id=r.id;
        continue;
      end if;
      raise exception 'research_review_actor_missing_requires_reconciliation' using errcode='23514';
    end if;

    v_note_hash:=case
      when nullif(btrim(coalesce(r.review_note,'')),'') is null then null
      else encode(extensions.digest(convert_to(btrim(r.review_note),'UTF8'),'sha256'),'hex')
    end;
    v_event_hash:=public.echo_research_review_event_hash_v1(
      r.id,r.contributor_id,r.knowledge_fingerprint,1,'pending',r.status,false,r.is_first_discovery,
      r.reviewed_by,coalesce(r.reviewed_at,r.updated_at,r.submitted_at),v_note_hash,null,r.guardrail_policy_version
    );
    insert into public.echo_research_review_events(
      contribution_id,contributor_id,knowledge_fingerprint,revision,previous_status,new_status,
      previous_first_discovery,new_first_discovery,reviewer_id,reviewed_at,review_note_hash,
      previous_event_hash,event_hash,guardrail_policy_version,created_at
    ) values(
      r.id,r.contributor_id,r.knowledge_fingerprint,1,'pending',r.status,false,r.is_first_discovery,
      r.reviewed_by,coalesce(r.reviewed_at,r.updated_at,r.submitted_at),v_note_hash,
      null,v_event_hash,r.guardrail_policy_version,coalesce(r.reviewed_at,r.updated_at,r.submitted_at)
    ) returning id into v_event_id;

    v_state:=case
      when r.status='superseded' then 'not_applicable'
      when r.reviewed_by=r.contributor_id then 'ineligible_self_review'
      else 'awaiting_confirmation'
    end;
    update public.echo_research_contributions
    set review_revision=1,current_review_event_id=v_event_id,review_confirmation_state=v_state
    where id=r.id;
  end loop;
end $$;

