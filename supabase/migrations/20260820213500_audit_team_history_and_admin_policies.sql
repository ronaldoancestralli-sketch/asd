-- Histórico permanente da Auditoria e políticas administrativas.
-- Objetivos:
-- 1) registrar decisões de classificação e mudanças nas regras de bônus;
-- 2) permitir rastreabilidade quando várias pessoas trabalham no painel;
-- 3) impedir que usuários autenticados comuns alterem a fila/classificações.

create or replace function public.echo_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    left join public.roles r on r.id = p.role_id
    where p.id = auth.uid()
      and (
        coalesce(p.is_admin, false) = true
        or lower(coalesce(p.role, '')) = 'admin'
        or lower(coalesce(r.name, '')) = 'admin'
      )
  );
$$;

revoke all on function public.echo_is_admin() from public;
grant execute on function public.echo_is_admin() to authenticated;

-- Mantém leitura pública somente das classificações ativas, pois o frontend
-- usa essas decisões para explicar efeitos não calculados. Escritas ficam
-- restritas a administradores reais do painel.
drop policy if exists equipment_attribute_classifications_authenticated_insert on public.equipment_attribute_classifications;
drop policy if exists equipment_attribute_classifications_authenticated_update on public.equipment_attribute_classifications;
drop policy if exists equipment_attribute_classifications_authenticated_delete on public.equipment_attribute_classifications;

create policy equipment_attribute_classifications_admin_insert
  on public.equipment_attribute_classifications
  for insert to authenticated
  with check (public.echo_is_admin());

create policy equipment_attribute_classifications_admin_update
  on public.equipment_attribute_classifications
  for update to authenticated
  using (public.echo_is_admin())
  with check (public.echo_is_admin());

create policy equipment_attribute_classifications_admin_delete
  on public.equipment_attribute_classifications
  for delete to authenticated
  using (public.echo_is_admin());

-- A fila da Auditoria é administrativa. Usuários autenticados comuns não
