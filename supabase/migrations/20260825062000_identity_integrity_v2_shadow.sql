-- Echo Identity Integrity V2 — hardening adicional em Shadow.
-- Anti-impersonação, deduplicação de Creator/Echo Research e rollout fail-closed.
-- NÃO altera a experiência pública enquanto os gates permanecerem desligados.

begin;

-- ---------------------------------------------------------------------------
-- 1. Gate de rollout: master + capacidades, todas desligadas por padrão.
-- ---------------------------------------------------------------------------
create table if not exists public.echo_identity_rollout_settings (
  singleton boolean primary key default true check (singleton=true),
  schema_version text not null default 'identity-integrity-v2-shadow',
  public_identity_enabled boolean not null default false,
  signup_handle_enabled boolean not null default false,
  public_profiles_enabled boolean not null default false,
  identity_cards_enabled boolean not null default false,
  creator_verification_enabled boolean not null default false,
  research_submission_enabled boolean not null default false,
  updated_by uuid references public.profiles(id) on delete set null,
  last_change_reason text,
  updated_at timestamptz not null default now(),
  constraint echo_identity_rollout_master_guard check (
    public_identity_enabled
    or not (signup_handle_enabled or public_profiles_enabled or identity_cards_enabled or creator_verification_enabled or research_submission_enabled)
  ),
  constraint echo_identity_rollout_reason_length check (last_change_reason is null or char_length(last_change_reason)<=1000)
);

create table if not exists public.echo_identity_rollout_audit (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references public.profiles(id) on delete set null,
  before_state jsonb not null,
  after_state jsonb not null,
  reason text,
  created_at timestamptz not null default now(),
  constraint echo_identity_rollout_audit_reason_length check (reason is null or char_length(reason)<=1000),
  constraint echo_identity_rollout_audit_before_size check (octet_length(before_state::text)<=16384),
  constraint echo_identity_rollout_audit_after_size check (octet_length(after_state::text)<=16384)
);

insert into public.echo_identity_rollout_settings(singleton)
values(true)
on conflict(singleton) do nothing;

