create or replace function public.echo_brain_mark_hero_profile_dirty()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_hero_id text;
  v_reason jsonb;
begin
  if tg_table_name = 'heroes' then
    v_hero_id := case when tg_op='DELETE' then old.id::text else new.id::text end;
  else
    v_hero_id := case when tg_op='DELETE' then old.hero_id::text else new.hero_id::text end;
  end if;
  if coalesce(v_hero_id,'')='' then return null; end if;
  v_reason := jsonb_build_object('table',tg_table_name,'operation',tg_op,'at',now());
  insert into public.echo_brain_knowledge_change_queue(entity_type,entity_id,source,reasons,status,updated_at,resolved_at)
  values('hero_profile',v_hero_id,'database-trigger',jsonb_build_array(v_reason),'pending',now(),null)
  on conflict(entity_type,entity_id) do update set
    reasons=public.echo_brain_knowledge_change_queue.reasons || jsonb_build_array(v_reason),
    source='database-trigger',status='pending',updated_at=now(),resolved_at=null;
  return null;
end;
$$;

revoke all on function public.echo_brain_mark_hero_profile_dirty() from public, anon, authenticated;

drop trigger if exists trg_echo_brain_hero_profile_dirty on public.heroes;
create trigger trg_echo_brain_hero_profile_dirty after insert or update or delete on public.heroes
for each row execute function public.echo_brain_mark_hero_profile_dirty();

drop trigger if exists trg_echo_brain_hero_skill_dirty on public.hero_skills;
create trigger trg_echo_brain_hero_skill_dirty after insert or update or delete on public.hero_skills
for each row execute function public.echo_brain_mark_hero_profile_dirty();

drop trigger if exists trg_echo_brain_hero_base_stats_dirty on public.hero_base_stats;
create trigger trg_echo_brain_hero_base_stats_dirty after insert or update or delete on public.hero_base_stats
