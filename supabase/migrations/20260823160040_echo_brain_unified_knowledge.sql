-- Readiness do futuro simulador: somente diagnóstico. Não habilita simulador.
create or replace function public.admin_echo_brain_simulation_readiness()
returns jsonb
language plpgsql
stable
security definer
set search_path=public,pg_temp
as $$
declare v_knowledge bigint; v_equipment bigint; v_sim bigint;
begin
  if not public.echo_is_admin() then raise exception 'admin_required' using errcode='42501'; end if;
  select count(*) into v_knowledge from public.echo_brain_knowledge_change_queue where status in ('pending','processing');
  select count(*) into v_equipment from public.equipment_brain_change_queue where status in ('pending','processing');
  select count(*) into v_sim from public.echo_brain_knowledge_invalidations where status='pending' and scope='simulation_readiness';
  return jsonb_build_object(
    'ready', (v_knowledge=0 and v_equipment=0 and v_sim=0),
    'simulatorEnabled', false,
    'knowledgePending',v_knowledge,
    'equipmentPending',v_equipment,
    'simulationInvalidations',v_sim,
    'contract','verified-rules-first-v1'
  );
end;
$$;
