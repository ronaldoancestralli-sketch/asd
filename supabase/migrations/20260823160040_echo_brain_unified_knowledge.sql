  select count(*) into v_edges from public.echo_brain_semantic_edges where active is true;
  return jsonb_build_object('pendingKnowledge',v_pending,'pendingInvalidations',v_invalid,'heroVersions',v_hero_versions,'equipmentVersions',v_equipment_versions,'semanticEdges',v_edges);
end;
$$;
