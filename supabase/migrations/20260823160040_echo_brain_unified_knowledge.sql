-- Instalação fail-safe: nenhum herói existente começa falsamente como atual.
insert into public.echo_brain_knowledge_change_queue(entity_type,entity_id,source,reasons,status)
select 'hero_profile', h.id::text, 'migration-bootstrap',
       jsonb_build_array(jsonb_build_object('operation','baseline_required','at',now())), 'pending'
from public.heroes h
on conflict(entity_type,entity_id) do nothing;

create or replace function public.admin_echo_brain_reconcile_knowledge(p_limit integer default 100)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  r record;
  v_snapshot jsonb;
  v_previous public.echo_brain_knowledge_versions%rowtype;
  v_fingerprint text;
  v_version integer;
  v_version_id bigint;
  v_season_id uuid;
  v_game_version text;
  v_changed boolean;
  v_processed integer := 0;
  v_versioned integer := 0;
  v_unchanged integer := 0;
begin
  if not public.echo_is_admin() then raise exception 'admin_required' using errcode='42501'; end if;
  select id,game_version into v_season_id,v_game_version from public.seasons
  where active is true order by starts_at desc nulls last,created_at desc limit 1;

  for r in
    select * from public.echo_brain_knowledge_change_queue
    where status in ('pending','processing') order by updated_at asc limit greatest(1,least(coalesce(p_limit,100),500))
    for update skip locked
  loop
    v_processed := v_processed + 1;
    update public.echo_brain_knowledge_change_queue set status='processing',updated_at=now()
    where entity_type=r.entity_type and entity_id=r.entity_id;

    if r.entity_type='hero_profile' then
      select jsonb_build_object(
        'hero', to_jsonb(h),
        'skills', coalesce((select jsonb_agg(to_jsonb(s) order by s.display_order,s.id) from public.hero_skills s where s.hero_id=h.id),'[]'::jsonb),
        'baseStats', coalesce((select jsonb_object_agg(b.stat_key,b.value order by b.stat_key) from public.hero_base_stats b where b.hero_id=h.id),'{}'::jsonb),
        'weaponStats', coalesce((select jsonb_object_agg(w.stat_key,w.value order by w.stat_key) from public.hero_weapon_stats w where w.hero_id=h.id),'{}'::jsonb)
      ) into v_snapshot
      from public.heroes h where h.id::text=r.entity_id;
      if v_snapshot is null then
        v_snapshot := jsonb_build_object('hero',jsonb_build_object('id',r.entity_id,'deleted',true),'skills','[]'::jsonb,'baseStats','{}'::jsonb,'weaponStats','{}'::jsonb);
      end if;
    else
      v_snapshot := jsonb_build_object('entityType',r.entity_type,'entityId',r.entity_id);
    end if;

    v_fingerprint := md5(v_snapshot::text);
    select * into v_previous from public.echo_brain_knowledge_versions
    where entity_type=r.entity_type and entity_id=r.entity_id order by version desc limit 1;
    v_changed := not found or v_previous.semantic_fingerprint<>v_fingerprint;

    if not v_changed then
      update public.echo_brain_knowledge_change_queue set status='resolved',resolved_at=now(),updated_at=now()
      where entity_type=r.entity_type and entity_id=r.entity_id;
      v_unchanged := v_unchanged + 1;
      continue;
    end if;

    perform pg_advisory_xact_lock(hashtextextended(r.entity_type||':'||r.entity_id,0));
    select coalesce(max(version),0)+1 into v_version from public.echo_brain_knowledge_versions
    where entity_type=r.entity_type and entity_id=r.entity_id;

    insert into public.echo_brain_knowledge_versions(
      entity_type,entity_id,version,season_id,game_version,source,change_class,semantic_fingerprint,snapshot,created_by
    ) values (
      r.entity_type,r.entity_id,v_version,v_season_id,v_game_version,r.source,
      case when v_previous.id is null then 'baseline' else 'knowledge_change' end,
      v_fingerprint,v_snapshot,auth.uid()
    ) returning id into v_version_id;

    if v_previous.id is not null then
      insert into public.echo_brain_knowledge_invalidations(knowledge_version_id,entity_type,entity_id,scope,reason,metadata)
      values
        (v_version_id,r.entity_type,r.entity_id,'build_recommendations','hero_profile_changed',jsonb_build_object('gameVersion',v_game_version)),
        (v_version_id,r.entity_type,r.entity_id,'composition_recommendations','hero_profile_changed',jsonb_build_object('gameVersion',v_game_version)),
        (v_version_id,r.entity_type,r.entity_id,'training','hero_profile_changed',jsonb_build_object('gameVersion',v_game_version)),
        (v_version_id,r.entity_type,r.entity_id,'simulation_readiness','hero_profile_changed',jsonb_build_object('gameVersion',v_game_version))
      on conflict(knowledge_version_id,scope) do nothing;
    end if;

    update public.echo_brain_knowledge_change_queue set status='resolved',resolved_at=now(),updated_at=now()
    where entity_type=r.entity_type and entity_id=r.entity_id;
    v_versioned := v_versioned + 1;
  end loop;

  return jsonb_build_object('ok',true,'processed',v_processed,'versioned',v_versioned,'unchanged',v_unchanged,'seasonId',v_season_id,'gameVersion',v_game_version);
end;
$$;

revoke all on function public.admin_echo_brain_reconcile_knowledge(integer) from public, anon;
grant execute on function public.admin_echo_brain_reconcile_knowledge(integer) to authenticated;

create or replace view public.echo_brain_current_knowledge
with (security_invoker=true) as
select 'hero_profile'::text as entity_type, v.entity_id, v.version, v.game_version,
       v.semantic_fingerprint, v.created_at, v.snapshot
from public.echo_brain_knowledge_versions v
join (
  select entity_type,entity_id,max(version) version from public.echo_brain_knowledge_versions group by entity_type,entity_id
) x on x.entity_type=v.entity_type and x.entity_id=v.entity_id and x.version=v.version
union all
select 'equipment'::text, e.equipment_id, e.version, e.game_version,
       e.semantic_fingerprint, e.created_at, e.after_snapshot
from public.equipment_brain_versions e
join (
  select equipment_id,max(version) version from public.equipment_brain_versions group by equipment_id
) y on y.equipment_id=e.equipment_id and y.version=e.version;

revoke all on public.echo_brain_current_knowledge from anon, authenticated;
grant select on public.echo_brain_current_knowledge to authenticated;

