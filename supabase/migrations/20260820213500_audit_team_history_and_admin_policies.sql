create policy equipment_audit_queue_admin_select
  on public.equipment_audit_queue
  for select to authenticated
  using (public.echo_is_admin());

create policy equipment_audit_queue_admin_insert
  on public.equipment_audit_queue
  for insert to authenticated
  with check (public.echo_is_admin());

create policy equipment_audit_queue_admin_update
  on public.equipment_audit_queue
  for update to authenticated
  using (public.echo_is_admin())
  with check (public.echo_is_admin());

