create or replace function public.echo_identity_display_name_reserved(p_display text)
returns boolean
language sql
immutable
set search_path=''
as $$
  with n as (
    select lower(regexp_replace(btrim(coalesce(p_display,'')),'[[:space:]]+',' ','g')) as value
  )
  select value = any(array[
      'admin','administrator','administrador','moderator','moderador','mod','developer','desenvolvedor','dev',
      'founder','fundador','fundadora','owner','creator','criador','partner','parceiro','support','suporte',
      'staff','official','oficial','echoarena','echo arena','zeptolab','bullet echo','bulletecho'
    ]::text[])
    or value ~ '^(echo ?arena|zeptolab|bullet ?echo)[ ._-]*(admin|staff|support|suporte|official|oficial|moderator|moderador|developer|dev)$'
  from n;
$$;
revoke all on function public.echo_identity_display_name_reserved(text) from public,anon,authenticated;

-- ---------------------------------------------------------------------------
-- 3. Creator: fingerprint de canal e propriedade verificada exclusiva.
-- A normalização é conservadora: trim + remoção de barras finais; não altera path.
-- ---------------------------------------------------------------------------
create or replace function public.echo_creator_channel_fingerprint(p_url text)
returns text
language sql
immutable
set search_path=''
as $$
  select encode(
    extensions.digest(
      convert_to(regexp_replace(btrim(coalesce(p_url,'')),'/+$','','g'),'UTF8'),
      'sha256'
    ),
    'hex'
  );
$$;
