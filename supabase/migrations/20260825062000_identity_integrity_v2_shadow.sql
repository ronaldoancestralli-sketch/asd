      'public_identity_enabled',new.public_identity_enabled,
      'signup_handle_enabled',new.signup_handle_enabled,
      'public_profiles_enabled',new.public_profiles_enabled,
      'identity_cards_enabled',new.identity_cards_enabled,
      'creator_verification_enabled',new.creator_verification_enabled,
      'research_submission_enabled',new.research_submission_enabled
    ),
    new.last_change_reason
