create or replace function public.echo_brain_register_recommendation_exposure(
  p_surface text,
  p_entity_key text,
  p_semantic_schema text default null,
  p_model_id uuid default null,
  p_model_version integer default null,
  p_brain_influence numeric default 0,
  p_context_hash text default null
)
returns uuid
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare v_id uuid;
begin
  if coalesce(p_surface,'') not in ('composition_lab','build_lab','comparison','other') then raise exception 'invalid_surface'; end if;
  if coalesce(trim(p_entity_key),'')='' then raise exception 'entity_key_required'; end if;
  insert into public.echo_brain_recommendation_exposures(surface,entity_key,semantic_schema,model_id,model_version,brain_influence,context_hash)
  values(p_surface,p_entity_key,p_semantic_schema,p_model_id,p_model_version,least(.55,greatest(0,coalesce(p_brain_influence,0))),p_context_hash)
  returning id into v_id;
  return v_id;
end;
$$;
