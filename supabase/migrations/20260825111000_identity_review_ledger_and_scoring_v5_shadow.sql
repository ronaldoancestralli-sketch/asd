create or replace function public.admin_confirm_research_review_v1(
  p_contribution_id uuid,
  p_decision_event_id bigint,
  p_outcome text,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_uid uuid:=auth.uid();
  v_row public.echo_research_contributions%rowtype;
  v_event public.echo_research_review_events%rowtype;
  v_id uuid:=extensions.gen_random_uuid();
  v_created_at timestamptz:=clock_timestamp();
  v_note text:=nullif(btrim(coalesce(p_note,'')),'');
  v_note_hash text;
  v_confirmation_hash text;
begin
  if not public.echo_is_admin() then raise exception 'admin_aal2_required' using errcode='42501'; end if;
  if p_outcome not in ('confirmed','disputed') then
    raise exception 'invalid_research_confirmation_outcome' using errcode='22023';
  end if;
  if p_note is not null and char_length(p_note)>1600 then
    raise exception 'research_confirmation_note_too_long' using errcode='22023';
  end if;
  if p_outcome='disputed' and v_note is null then
    raise exception 'research_dispute_reason_required' using errcode='22023';
  end if;

  select * into v_row
  from public.echo_research_contributions
  where id=p_contribution_id
  for update;
  if not found then raise exception 'research_contribution_not_found' using errcode='22023'; end if;
  if v_row.current_review_event_id is distinct from p_decision_event_id then
    raise exception 'research_confirmation_stale_decision' using errcode='40001';
  end if;
  if v_row.review_confirmation_state<>'awaiting_confirmation' then
    raise exception 'research_decision_not_awaiting_confirmation' using errcode='22023';
  end if;

  select * into v_event
  from public.echo_research_review_events
  where id=p_decision_event_id and contribution_id=p_contribution_id
  for share;
  if not found then raise exception 'research_review_event_not_found' using errcode='22023'; end if;
  if v_event.reviewer_id=v_uid then
    raise exception 'research_reviewer_cannot_self_confirm' using errcode='42501';
  end if;
  if v_event.contributor_id=v_uid then
    raise exception 'research_contributor_cannot_confirm' using errcode='42501';
  end if;
  if v_event.reviewer_id=v_event.contributor_id then
    raise exception 'self_review_not_confirmation_eligible' using errcode='42501';
  end if;

  v_note_hash:=case when v_note is null then null
    else encode(extensions.digest(convert_to(v_note,'UTF8'),'sha256'),'hex') end;
  v_confirmation_hash:=encode(
    extensions.digest(
      convert_to(
        jsonb_build_object(
          'confirmation_id',v_id,
          'decision_event_id',v_event.id,
          'decision_event_hash',v_event.event_hash,
          'contribution_id',v_row.id,
          'confirmer_id',v_uid,
          'outcome',p_outcome,
          'confirmation_note_hash',v_note_hash,
          'created_at_epoch_us',(extract(epoch from v_created_at)*1000000)::bigint
        )::text,
        'UTF8'
      ),
      'sha256'
    ),
    'hex'
  );

  begin
    insert into public.echo_research_review_confirmations(
      id,decision_event_id,contribution_id,confirmer_id,outcome,confirmation_note,
      confirmation_note_hash,confirmation_hash,created_at
    ) values(
      v_id,v_event.id,v_row.id,v_uid,p_outcome,v_note,v_note_hash,v_confirmation_hash,v_created_at
    );
  exception when unique_violation then
    raise exception 'research_decision_already_confirmed' using errcode='23505';
  end;

  update public.echo_research_contributions
  set review_confirmation_state=p_outcome
  where id=v_row.id;

  perform public.echo_recompute_community_reputation(v_row.contributor_id);

  return jsonb_build_object(
    'contribution_id',v_row.id,
    'decision_event_id',v_event.id,
    'outcome',p_outcome,
    'confirmation_hash',v_confirmation_hash,
    'reputation_recomputed',true
  );
end;
$$;
revoke all on function public.admin_confirm_research_review_v1(uuid,bigint,text,text) from public,anon;
grant execute on function public.admin_confirm_research_review_v1(uuid,bigint,text,text) to authenticated,service_role;

-- A tabela-base contém payload/evidência e notas internas. Membros recebem
-- apenas colunas seguras; o painel AAL2 usa esta fila privilegiada e estreita.
create or replace function public.admin_research_review_queue_v5(
  p_queue text default 'all',
  p_limit integer default 80
)
returns setof public.echo_research_contributions
language plpgsql
security definer
stable
set search_path=''
as $$
declare
  v_limit integer:=least(100,greatest(1,coalesce(p_limit,80)));
begin
  if not public.echo_is_admin() then raise exception 'admin_aal2_required' using errcode='42501'; end if;
  if p_queue not in ('pending','confirmation','all') then
    raise exception 'invalid_research_review_queue' using errcode='22023';
  end if;

  if p_queue = 'pending' then
    return query
    select c.*
    from public.echo_research_contributions c
    where c.status='pending'
    order by c.submitted_at, c.id
    limit v_limit;
    return;
  end if;

  if p_queue = 'confirmation' then
    return query
    select c.*
    from public.echo_research_contributions c
    where c.review_confirmation_state='awaiting_confirmation'
    order by c.reviewed_at, c.id
    limit v_limit;
    return;
  end if;

  return query
  select c.*
  from public.echo_research_contributions c
  where c.status='pending'
     or c.review_confirmation_state='awaiting_confirmation'
  order by coalesce(c.reviewed_at,c.submitted_at),c.id
  limit v_limit;
end;
$$;
revoke all on function public.admin_research_review_queue_v5(text,integer) from public,anon;
grant execute on function public.admin_research_review_queue_v5(text,integer) to authenticated,service_role;

