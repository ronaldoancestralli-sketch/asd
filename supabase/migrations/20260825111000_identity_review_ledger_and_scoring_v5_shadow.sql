create or replace function public.echo_identity_authority_audit_chain_v5()
returns trigger
language plpgsql
security definer
set search_path=''
as $$
declare
  v_previous text;
begin
  select s.last_event_hash into v_previous
  from public.echo_identity_authority_audit_chain_state s
  where s.singleton=true
  for update;

  new.previous_event_hash:=v_previous;
  new.chain_version:=coalesce(nullif(new.chain_version,''),'authority-audit-v5');
  new.event_hash:=public.echo_identity_authority_event_hash_v1(
    new.id,new.previous_event_hash,new.target_user_id,new.authority_kind,new.authority_value,new.action,
    new.actor_user_id,new.actor_role,new.reason,new.context,new.created_at,new.chain_version
  );

  update public.echo_identity_authority_audit_chain_state
  set last_event_id=new.id,last_event_hash=new.event_hash,updated_at=now()
  where singleton=true;
  return new;
end;
$$;
