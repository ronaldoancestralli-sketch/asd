as $$
declare
  v_pending bigint;
  v_invalid bigint;
  v_hero_versions bigint;
  v_equipment_versions bigint;
  v_edges bigint;
begin
  if not public.echo_is_admin() then raise exception 'admin_required' using errcode='42501'; end if;
  select count(*) into v_pending from public.echo_brain_knowledge_change_queue where status in ('pending','processing');
  select count(*) into v_invalid from public.echo_brain_knowledge_invalidations where status='pending';
