  'Tempo de troca de modo da arma primária percentual',
  'external_data_required',
  'Tempo de troca de modo da arma primária',
  'O efeito é real, mas o jogo não disponibiliza publicamente a base e a regra interna necessárias para calcular o tempo final com segurança.',
