create or replace function public.echo_research_review_ledger_before_update_v5()
returns trigger
language plpgsql
security definer
set search_path=''
as $$
declare
  v_previous_hash text;
  v_note_hash text;
  v_event_hash text;
  v_event_id bigint;
  v_revision integer;
begin
  if new.status is not distinct from old.status
     and new.is_first_discovery is not distinct from old.is_first_discovery
     and new.reviewed_by is not distinct from old.reviewed_by
     and new.reviewed_at is not distinct from old.reviewed_at
     and new.review_note is not distinct from old.review_note then
    return new;
  end if;

  if new.status='pending' then
    raise exception 'research_review_cannot_return_pending' using errcode='22023';
  end if;
  if new.reviewed_by is null or new.reviewed_at is null then
    raise exception 'research_review_actor_and_time_required' using errcode='23514';
  end if;
  if new.is_first_discovery and new.status<>'verified' then
    raise exception 'first_discovery_requires_verified' using errcode='22023';
  end if;

  if old.review_revision=0 then
    if old.current_review_event_id is not null then
      raise exception 'research_review_pointer_corrupt' using errcode='23514';
    end if;
    v_previous_hash:=null;
  else
    select e.event_hash into v_previous_hash
    from public.echo_research_review_events e
    where e.id=old.current_review_event_id and e.contribution_id=old.id and e.revision=old.review_revision;
    if v_previous_hash is null then
      raise exception 'research_review_chain_missing' using errcode='23514';
    end if;
  end if;

  v_revision:=old.review_revision+1;
  v_note_hash:=case
    when nullif(btrim(coalesce(new.review_note,'')),'') is null then null
    else encode(extensions.digest(convert_to(btrim(new.review_note),'UTF8'),'sha256'),'hex')
  end;
  v_event_hash:=public.echo_research_review_event_hash_v1(
    new.id,new.contributor_id,new.knowledge_fingerprint,v_revision,old.status,new.status,
    old.is_first_discovery,new.is_first_discovery,new.reviewed_by,new.reviewed_at,
    v_note_hash,v_previous_hash,new.guardrail_policy_version
  );

  insert into public.echo_research_review_events(
    contribution_id,contributor_id,knowledge_fingerprint,revision,previous_status,new_status,
    previous_first_discovery,new_first_discovery,reviewer_id,reviewed_at,review_note_hash,
    previous_event_hash,event_hash,guardrail_policy_version,created_at
  ) values(
    new.id,new.contributor_id,new.knowledge_fingerprint,v_revision,old.status,new.status,
    old.is_first_discovery,new.is_first_discovery,new.reviewed_by,new.reviewed_at,
    v_note_hash,v_previous_hash,v_event_hash,new.guardrail_policy_version,new.reviewed_at
  ) returning id into v_event_id;

  new.review_revision:=v_revision;
  new.current_review_event_id:=v_event_id;
  new.review_confirmation_state:=case
    when new.status='superseded' then 'not_applicable'
    when new.reviewed_by=new.contributor_id then 'ineligible_self_review'
    else 'awaiting_confirmation'
  end;
  return new;
end;
$$;
revoke all on function public.echo_research_review_ledger_before_update_v5() from public,anon,authenticated,service_role;

