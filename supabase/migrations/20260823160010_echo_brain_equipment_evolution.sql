-- Echo Brain — memória versionada de evolução de equipamentos.
-- Objetivo: buffs, nerfs, mudanças de comportamento, raridade e bônus de conjunto
-- nunca sobrescrevem silenciosamente o conhecimento anterior do Brain.

create table if not exists public.equipment_brain_versions (
  id bigint generated by default as identity primary key,
  equipment_id text not null,
  version integer not null check (version > 0),
  season_id uuid references public.seasons(id) on delete set null,
  game_version text,
  source text not null default 'admin-editor',
  change_class text not null default 'mixed_change',
  severity text not null default 'medium' check (severity in ('none','low','medium','high','critical')),
  affects_brain boolean not null default false,
  requires_reevaluation boolean not null default false,
  requires_retraining boolean not null default false,
  semantic_fingerprint text not null,
  before_snapshot jsonb,
  after_snapshot jsonb not null,
  analysis jsonb not null default '{}'::jsonb,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (equipment_id, version)
);

create index if not exists equipment_brain_versions_equipment_idx
  on public.equipment_brain_versions (equipment_id, version desc);
create index if not exists equipment_brain_versions_season_idx
  on public.equipment_brain_versions (season_id, created_at desc);
create index if not exists equipment_brain_versions_change_idx
  on public.equipment_brain_versions (affects_brain, requires_retraining, created_at desc);

create table if not exists public.equipment_brain_invalidations (
  id bigint generated by default as identity primary key,
  equipment_id text not null,
  equipment_version_id bigint not null references public.equipment_brain_versions(id) on delete cascade,
  scope text not null check (scope in ('item_fit','build_recommendations','composition_recommendations','training')),
  status text not null default 'pending' check (status in ('pending','resolved','ignored')),
  reason text not null default '',
  affected_rarities text[] not null default '{}'::text[],
  affected_attributes text[] not null default '{}'::text[],
  metadata jsonb not null default '{}'::jsonb,
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  unique (equipment_version_id, scope)
);

create index if not exists equipment_brain_invalidations_pending_idx
  on public.equipment_brain_invalidations (status, scope, created_at desc);
create index if not exists equipment_brain_invalidations_equipment_idx
  on public.equipment_brain_invalidations (equipment_id, status, created_at desc);

-- Fila fail-safe: os triggers marcam o item como alterado mesmo se a etapa de
-- análise semântica no navegador falhar. Assim o Brain nunca considera silêncio
-- de integração como prova de que o conhecimento está atualizado.
create table if not exists public.equipment_brain_change_queue (
  equipment_id text primary key,
  source text not null default 'database-trigger',
  reasons jsonb not null default '[]'::jsonb,
  status text not null default 'pending' check (status in ('pending','processing','resolved','ignored')),
  first_seen_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz
);

create index if not exists equipment_brain_change_queue_status_idx
  on public.equipment_brain_change_queue (status, updated_at desc);

-- A primeira instalação NÃO considera 0 versões como conhecimento atual.
-- Todo equipamento já existente começa como baseline pendente e só sai da fila
-- depois de receber um snapshot versionado pelo reconciliador administrativo.
insert into public.equipment_brain_change_queue(
  equipment_id, source, reasons, status, first_seen_at, updated_at, resolved_at
)
select
  e.id::text,
  'migration-bootstrap',
  jsonb_build_array(jsonb_build_object(
    'table','equipments',
    'operation','BASELINE_REQUIRED',
    'at',now()
  )),
  'pending',
  now(),
  now(),
  null
from public.equipments e
on conflict (equipment_id) do nothing;

alter table public.equipment_brain_versions enable row level security;
alter table public.equipment_brain_invalidations enable row level security;
alter table public.equipment_brain_change_queue enable row level security;

revoke all on table public.equipment_brain_versions from anon, authenticated;
revoke all on table public.equipment_brain_invalidations from anon, authenticated;
revoke all on table public.equipment_brain_change_queue from anon, authenticated;

grant select on table public.equipment_brain_versions to authenticated;
grant select, update on table public.equipment_brain_invalidations to authenticated;
grant select, update on table public.equipment_brain_change_queue to authenticated;

