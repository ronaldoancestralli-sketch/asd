-- Echo Identity V5 Shadow — Review Ledger + Confirmed Scoring.
-- Toda decisão fica encadeada e imutável. Reputação só usa decisão confirmada
-- por um segundo Admin AAL2 independente do autor e do primeiro revisor.
-- Destino exclusivo: Supabase SNV. Não habilita rollout público.

begin;

-- ---------------------------------------------------------------------------
-- 1. Ledger de decisões por contribuição.
-- ---------------------------------------------------------------------------
create table if not exists public.echo_research_review_events (
  id bigint generated by default as identity primary key,
  contribution_id uuid not null references public.echo_research_contributions(id) on delete restrict,
  contributor_id uuid not null references public.profiles(id) on delete restrict,
  knowledge_fingerprint text not null,
  revision integer not null check (revision>=1),
  previous_status text not null check (previous_status in ('pending','corroborated','verified','rejected','contested','superseded')),
  new_status text not null check (new_status in ('corroborated','verified','rejected','contested','superseded')),
  previous_first_discovery boolean not null,
  new_first_discovery boolean not null,
  reviewer_id uuid not null references public.profiles(id) on delete restrict,
  reviewed_at timestamptz not null,
  review_note_hash text,
  previous_event_hash text,
  event_hash text not null unique,
  guardrail_policy_version text not null,
  created_at timestamptz not null default now(),
  unique(contribution_id,revision),
  constraint echo_research_review_event_knowledge_hash check (knowledge_fingerprint ~ '^[a-f0-9]{64}$'),
  constraint echo_research_review_event_note_hash check (review_note_hash is null or review_note_hash ~ '^[a-f0-9]{64}$'),
  constraint echo_research_review_event_previous_hash check (previous_event_hash is null or previous_event_hash ~ '^[a-f0-9]{64}$'),
  constraint echo_research_review_event_hash check (event_hash ~ '^[a-f0-9]{64}$'),
  constraint echo_research_review_event_first_verified check (not new_first_discovery or new_status='verified')
);

create index if not exists echo_research_review_events_reviewer_idx
  on public.echo_research_review_events(reviewer_id,created_at desc);
create index if not exists echo_research_review_events_contributor_idx
  on public.echo_research_review_events(contributor_id,created_at desc);

create or replace function public.echo_research_review_event_hash_v1(
  p_contribution_id uuid,
  p_contributor_id uuid,
  p_knowledge_fingerprint text,
  p_revision integer,
  p_previous_status text,
  p_new_status text,
  p_previous_first boolean,
  p_new_first boolean,
  p_reviewer_id uuid,
  p_reviewed_at timestamptz,
  p_review_note_hash text,
  p_previous_event_hash text,
  p_policy_version text
)
returns text
language sql
stable
set search_path=''
as $$
  select encode(
    extensions.digest(
      convert_to(
        jsonb_build_object(
          'contribution_id',p_contribution_id,
          'contributor_id',p_contributor_id,
          'knowledge_fingerprint',p_knowledge_fingerprint,
          'revision',p_revision,
          'previous_status',p_previous_status,
          'new_status',p_new_status,
          'previous_first_discovery',p_previous_first,
          'new_first_discovery',p_new_first,
          'reviewer_id',p_reviewer_id,
          'reviewed_at_epoch_us',(extract(epoch from p_reviewed_at)*1000000)::bigint,
          'review_note_hash',p_review_note_hash,
          'previous_event_hash',p_previous_event_hash,
          'guardrail_policy_version',p_policy_version
        )::text,
        'UTF8'
      ),
      'sha256'
    ),
    'hex'
  );
$$;
revoke all on function public.echo_research_review_event_hash_v1(uuid,uuid,text,integer,text,text,boolean,boolean,uuid,timestamptz,text,text,text)
  from public,anon,authenticated,service_role;

