-- Echo Brain — fonte de verdade versionada, grafo, contrafactuais e proveniência.
-- Esta migration NÃO substitui equipment_brain_versions. Ela agrega a memória de
-- equipamentos existente com perfis completos de herói e contratos de decisão.

create table if not exists public.echo_brain_knowledge_versions (
  id bigint generated by default as identity primary key,
  entity_type text not null check (entity_type in ('hero_profile','ruleset')),
  entity_id text not null,
  version integer not null check (version > 0),
  season_id uuid references public.seasons(id) on delete set null,
  game_version text,
  source text not null default 'knowledge-reconcile',
  change_class text not null default 'knowledge_change',
  semantic_fingerprint text not null,
  snapshot jsonb not null,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique(entity_type, entity_id, version)
);

create index if not exists echo_brain_knowledge_versions_entity_idx
  on public.echo_brain_knowledge_versions(entity_type, entity_id, version desc);
create index if not exists echo_brain_knowledge_versions_season_idx
  on public.echo_brain_knowledge_versions(season_id, created_at desc);

create table if not exists public.echo_brain_knowledge_change_queue (
  entity_type text not null check (entity_type in ('hero_profile','ruleset')),
  entity_id text not null,
  source text not null default 'database-trigger',
  reasons jsonb not null default '[]'::jsonb,
  status text not null default 'pending' check (status in ('pending','processing','resolved','ignored')),
  first_seen_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz,
  primary key(entity_type, entity_id)
);

create table if not exists public.echo_brain_knowledge_invalidations (
  id bigint generated by default as identity primary key,
  knowledge_version_id bigint not null references public.echo_brain_knowledge_versions(id) on delete cascade,
  entity_type text not null,
  entity_id text not null,
  scope text not null check (scope in ('build_recommendations','composition_recommendations','training','simulation_readiness')),
  status text not null default 'pending' check (status in ('pending','resolved','ignored')),
  reason text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  resolved_at timestamptz,
  unique(knowledge_version_id, scope)
);

create index if not exists echo_brain_knowledge_invalidations_pending_idx
  on public.echo_brain_knowledge_invalidations(status, scope, created_at desc);

create table if not exists public.echo_brain_semantic_edges (
  id bigint generated by default as identity primary key,
  season_id uuid references public.seasons(id) on delete set null,
  game_version text,
  source_type text not null,
  source_id text not null,
  relation text not null,
  target_type text not null,
  target_id text not null,
  weight numeric(7,5) not null default 1 check (weight >= -1 and weight <= 1),
  confidence numeric(7,5) not null default 1 check (confidence >= 0 and confidence <= 1),
  evidence jsonb not null default '{}'::jsonb,
  source_fingerprint text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(season_id, source_type, source_id, relation, target_type, target_id, source_fingerprint)
);

create index if not exists echo_brain_semantic_edges_source_idx
  on public.echo_brain_semantic_edges(source_type, source_id, active);
create index if not exists echo_brain_semantic_edges_target_idx
  on public.echo_brain_semantic_edges(target_type, target_id, active);

create table if not exists public.echo_brain_decision_audits (
