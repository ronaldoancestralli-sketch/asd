-- ---------------------------------------------------------------------------
-- 5. Reforça RPC própria: anti-impersonação + rollout público fail-closed.
-- ---------------------------------------------------------------------------
create or replace function public.echo_set_my_public_identity_v1(
  p_handle text,
  p_display_name text,
  p_bio text default null,
  p_accent text default 'violet',
  p_visibility text default 'public',
  p_allow_messages boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_uid uuid := auth.uid();
  v_handle text := lower(btrim(coalesce(p_handle,'')));
  v_display text := btrim(coalesce(p_display_name,''));
  v_bio text := nullif(btrim(coalesce(p_bio,'')), '');
  v_current public.echo_public_profiles%rowtype;
begin
  if v_uid is null then raise exception 'authentication_required' using errcode='42501'; end if;
  if not exists(select 1 from public.profiles p where p.id=v_uid and coalesce(p.is_blocked,false)=false) then
    raise exception 'active_profile_required' using errcode='42501';
  end if;
  if v_handle !~ '^[a-z0-9](?:[a-z0-9._-]{1,22}[a-z0-9])$' then
    raise exception 'invalid_public_handle' using errcode='22023';
  end if;
  if public.echo_identity_handle_reserved(v_handle) then
    raise exception 'reserved_public_handle' using errcode='22023';
  end if;
  if char_length(v_display) not between 2 and 40 then
    raise exception 'invalid_display_name' using errcode='22023';
  end if;
  if public.echo_identity_display_name_has_invisible(v_display) then
    raise exception 'display_name_invisible_characters' using errcode='22023';
  end if;
  if public.echo_identity_display_name_reserved(v_display) then
    raise exception 'display_name_reserved' using errcode='22023';
  end if;
  if v_bio is not null and char_length(v_bio)>240 then raise exception 'bio_too_long' using errcode='22023'; end if;
  if p_accent not in ('violet','cyan','gold','emerald','rose','steel') then raise exception 'invalid_profile_accent' using errcode='22023'; end if;
  if p_visibility not in ('public','private') then raise exception 'invalid_profile_visibility' using errcode='22023'; end if;
  if p_visibility='public' and not exists(
    select 1 from public.echo_identity_rollout_settings s
    where s.singleton=true and s.public_identity_enabled=true and s.public_profiles_enabled=true
  ) then
    raise exception 'identity_public_rollout_disabled' using errcode='42501';
  end if;

  insert into public.echo_public_profiles(user_id,public_handle,profile_visibility)
  values(v_uid,public.echo_identity_generated_handle(v_uid),'private')
  on conflict(user_id) do nothing;

  select * into v_current from public.echo_public_profiles where user_id=v_uid for update;
  if v_current.public_handle<>v_handle
     and v_current.public_handle<>public.echo_identity_generated_handle(v_uid)
     and v_current.handle_changed_at is not null
     and v_current.handle_changed_at>now()-interval '30 days' then
    raise exception 'handle_change_cooldown' using errcode='42501';
  end if;

  begin
    update public.echo_public_profiles
    set public_handle=v_handle,bio=v_bio,profile_accent=p_accent,profile_visibility=p_visibility,
        allow_messages=coalesce(p_allow_messages,false),profile_completed_at=coalesce(profile_completed_at,now()),
        handle_changed_at=case when public_handle is distinct from v_handle then now() else handle_changed_at end
    where user_id=v_uid;
  exception when unique_violation then
    raise exception 'public_handle_unavailable' using errcode='23505';
  end;

  update public.profiles set display_name=v_display where id=v_uid;
  return jsonb_build_object(
    'user_id',v_uid,'public_handle',v_handle,'display_name',v_display,'bio',v_bio,
    'profile_accent',p_accent,'profile_visibility',p_visibility,'allow_messages',coalesce(p_allow_messages,false)
  );
end;
$$;
revoke all on function public.echo_set_my_public_identity_v1(text,text,text,text,text,boolean) from public,anon;
grant execute on function public.echo_set_my_public_identity_v1(text,text,text,text,text,boolean) to authenticated;

-- ---------------------------------------------------------------------------
-- 6. Creator request/review: gate, dedupe e unicidade de propriedade.
-- ---------------------------------------------------------------------------
create or replace function public.echo_request_creator_verification_v1(p_platform text,p_channel_url text)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_uid uuid:=auth.uid();
  v_code text;
  v_hash text;
  v_id uuid;
  v_fingerprint text;
begin
  if v_uid is null then raise exception 'authentication_required' using errcode='42501'; end if;
  if not exists(select 1 from public.profiles p where p.id=v_uid and coalesce(p.is_blocked,false)=false) then
    raise exception 'active_profile_required' using errcode='42501';
  end if;
  if not exists(select 1 from public.echo_identity_rollout_settings s where s.singleton=true and s.public_identity_enabled and s.creator_verification_enabled) then
    raise exception 'creator_verification_rollout_disabled' using errcode='42501';
  end if;
  if p_platform not in ('youtube','twitch','tiktok','instagram','facebook','x','other') then
    raise exception 'unsupported_creator_platform' using errcode='22023';
  end if;
  if p_channel_url is null or p_channel_url !~ '^https://' or char_length(p_channel_url)>1000 then
    raise exception 'invalid_creator_channel_url' using errcode='22023';
  end if;

  v_fingerprint:=public.echo_creator_channel_fingerprint(p_channel_url);
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(v_fingerprint,0));

  if exists(select 1 from public.echo_creator_claims c where c.channel_fingerprint=v_fingerprint and c.status='verified') then
    raise exception 'creator_channel_already_verified' using errcode='23505';
  end if;
  if exists(select 1 from public.echo_creator_claims c where c.user_id=v_uid and c.channel_fingerprint=v_fingerprint and c.status='pending' and c.expires_at>now()) then
    raise exception 'creator_claim_already_pending' using errcode='23505';
  end if;
  if (select count(*) from public.echo_creator_claims c where c.user_id=v_uid and c.requested_at>now()-interval '24 hours')>=5 then
    raise exception 'creator_claim_rate_limited' using errcode='42501';
  end if;
  if (select count(*) from public.echo_creator_claims c where c.user_id=v_uid and c.status='pending' and c.expires_at>now())>=3 then
    raise exception 'too_many_pending_creator_claims' using errcode='42501';
  end if;

  v_code:='ECHO-'||upper(substr(encode(extensions.gen_random_bytes(8),'hex'),1,10));
  v_hash:=encode(extensions.digest(convert_to(v_code,'UTF8'),'sha256'),'hex');
  insert into public.echo_creator_claims(user_id,platform,channel_url,channel_fingerprint,proof_code,proof_code_hash,expires_at)
  values(v_uid,p_platform,btrim(p_channel_url),v_fingerprint,v_code,v_hash,now()+interval '7 days')
  returning id into v_id;
  return jsonb_build_object('claim_id',v_id,'proof_code',v_code,'expires_at',now()+interval '7 days');
end;
$$;
revoke all on function public.echo_request_creator_verification_v1(text,text) from public,anon;
grant execute on function public.echo_request_creator_verification_v1(text,text) to authenticated;

create or replace function public.admin_review_creator_claim_v1(p_claim_id uuid,p_decision text,p_note text default null)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_claim public.echo_creator_claims%rowtype;
begin
  if not public.echo_is_admin() then raise exception 'admin_aal2_required' using errcode='42501'; end if;
  if p_decision not in ('verified','rejected') then raise exception 'invalid_creator_claim_decision' using errcode='22023'; end if;
  select * into v_claim from public.echo_creator_claims where id=p_claim_id for update;
  if not found then raise exception 'creator_claim_not_found' using errcode='22023'; end if;
  if v_claim.status<>'pending' then raise exception 'creator_claim_already_reviewed' using errcode='22023'; end if;
  if p_decision='verified' and v_claim.expires_at<=now() then
    update public.echo_creator_claims set status='expired',reviewed_by=auth.uid(),reviewed_at=now(),review_note='Desafio expirado antes da verificação.' where id=p_claim_id;
    raise exception 'creator_claim_expired' using errcode='22023';
  end if;
  if p_decision='verified' and exists(
    select 1 from public.echo_creator_claims c
    where c.id<>p_claim_id and c.channel_fingerprint=v_claim.channel_fingerprint and c.status='verified'
  ) then
    raise exception 'creator_channel_already_verified' using errcode='23505';
  end if;

  begin
    update public.echo_creator_claims
    set status=p_decision,reviewed_by=auth.uid(),reviewed_at=now(),review_note=nullif(btrim(coalesce(p_note,'')),'')
    where id=p_claim_id;
  exception when unique_violation then
    raise exception 'creator_channel_already_verified' using errcode='23505';
  end;

  if p_decision='verified' then
    perform public.admin_set_identity_badge_v1(v_claim.user_id,'creator',true,'Canal verificado por desafio EchoArena',v_claim.channel_url);
  end if;
  return jsonb_build_object('claim_id',p_claim_id,'status',p_decision,'user_id',v_claim.user_id);
end;
$$;
revoke all on function public.admin_review_creator_claim_v1(uuid,text,text) from public,anon;
grant execute on function public.admin_review_creator_claim_v1(uuid,text,text) to authenticated;

-- ---------------------------------------------------------------------------
-- 7. Echo Research submit: gate + fingerprint + lock transacional + janela.
-- ---------------------------------------------------------------------------
create or replace function public.echo_submit_research_contribution_v1(
  p_contribution_type text,
  p_subject_key text,
  p_payload jsonb default '{}'::jsonb,
  p_hero_id uuid default null,
  p_skill_id uuid default null,
  p_game_version text default null,
  p_evidence_kind text default 'text',
  p_evidence_reference text default null
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_uid uuid:=auth.uid();
  v_id uuid;
  v_payload jsonb:=coalesce(p_payload,'{}'::jsonb);
  v_fingerprint text;
begin
  if v_uid is null then raise exception 'authentication_required' using errcode='42501'; end if;
  if not exists(select 1 from public.profiles p where p.id=v_uid and coalesce(p.is_blocked,false)=false) then
    raise exception 'active_profile_required' using errcode='42501';
  end if;
  if not exists(select 1 from public.echo_identity_rollout_settings s where s.singleton=true and s.public_identity_enabled and s.research_submission_enabled) then
    raise exception 'research_submission_rollout_disabled' using errcode='42501';
  end if;
  if p_contribution_type not in ('hero_skill_level','hero_passive','equipment_stat','patch_change','counter_evidence','other') then
    raise exception 'invalid_contribution_type' using errcode='22023';
  end if;
  if char_length(btrim(coalesce(p_subject_key,''))) not between 1 and 160 then raise exception 'invalid_subject_key' using errcode='22023'; end if;
  if jsonb_typeof(v_payload)<>'object' or octet_length(v_payload::text)>16384 then raise exception 'invalid_contribution_payload' using errcode='22023'; end if;
  if p_evidence_kind not in ('screenshot','video','official_link','community_link','text','other') then raise exception 'invalid_evidence_kind' using errcode='22023'; end if;
  if p_evidence_reference is not null and char_length(p_evidence_reference)>1200 then raise exception 'evidence_reference_too_long' using errcode='22023'; end if;
  if (select count(*) from public.echo_research_contributions c where c.contributor_id=v_uid and c.submitted_at>now()-interval '24 hours')>=30 then
    raise exception 'research_submission_rate_limited' using errcode='42501';
  end if;

  v_fingerprint:=public.echo_research_submission_fingerprint(
    p_contribution_type,p_subject_key,v_payload,p_hero_id,p_skill_id,p_game_version,p_evidence_kind,p_evidence_reference
  );
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(v_uid::text||':'||v_fingerprint,0));

  if exists(
    select 1 from public.echo_research_contributions c
    where c.contributor_id=v_uid and c.submission_fingerprint=v_fingerprint
      and (c.status='pending' or c.submitted_at>now()-interval '7 days')
  ) then
    raise exception 'duplicate_research_submission' using errcode='23505';
  end if;

  insert into public.echo_research_contributions(
    contributor_id,contribution_type,hero_id,skill_id,subject_key,game_version,payload,evidence_kind,evidence_reference,
    submission_fingerprint,status,is_first_discovery
  ) values(
    v_uid,p_contribution_type,p_hero_id,p_skill_id,btrim(p_subject_key),nullif(btrim(coalesce(p_game_version,'')),''),
    v_payload,p_evidence_kind,nullif(btrim(coalesce(p_evidence_reference,'')),''),v_fingerprint,'pending',false
  ) returning id into v_id;
  return jsonb_build_object('contribution_id',v_id,'status','pending');
end;
$$;
revoke all on function public.echo_submit_research_contribution_v1(text,text,jsonb,uuid,uuid,text,text,text) from public,anon;
grant execute on function public.echo_submit_research_contribution_v1(text,text,jsonb,uuid,uuid,text,text,text) to authenticated;

