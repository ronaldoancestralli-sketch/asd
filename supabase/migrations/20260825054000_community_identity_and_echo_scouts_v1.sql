-- ---------------------------------------------------------------------------
-- 7. RPC de identidade própria. Apelido é ASCII normalizado para evitar homógrafos.
-- ---------------------------------------------------------------------------
create or replace function public.echo_set_my_public_identity_v1(
  p_handle text,
  p_display_name text,
  p_bio text default null,
  p_accent text default 'violet',
  p_visibility text default 'public',
  p_allow_messages boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_uid uuid := auth.uid();
  v_handle text := lower(btrim(coalesce(p_handle,'')));
  v_display text := btrim(coalesce(p_display_name,''));
  v_bio text := nullif(btrim(coalesce(p_bio,'')), '');
  v_current public.echo_public_profiles%rowtype;
begin
  if v_uid is null then
    raise exception 'authentication_required' using errcode='42501';
  end if;
  if not exists (select 1 from public.profiles p where p.id=v_uid and coalesce(p.is_blocked,false)=false) then
    raise exception 'active_profile_required' using errcode='42501';
  end if;
  if v_handle !~ '^[a-z0-9](?:[a-z0-9._-]{1,22}[a-z0-9])$' then
    raise exception 'invalid_public_handle' using errcode='22023';
  end if;
  if public.echo_identity_handle_reserved(v_handle) then
    raise exception 'reserved_public_handle' using errcode='22023';
  end if;
  if char_length(v_display) not between 2 and 40 then
    raise exception 'invalid_display_name' using errcode='22023';
  end if;
  if v_bio is not null and char_length(v_bio) > 240 then
    raise exception 'bio_too_long' using errcode='22023';
  end if;
  if p_accent not in ('violet','cyan','gold','emerald','rose','steel') then
    raise exception 'invalid_profile_accent' using errcode='22023';
  end if;
  if p_visibility not in ('public','private') then
    raise exception 'invalid_profile_visibility' using errcode='22023';
  end if;

  insert into public.echo_public_profiles(user_id,public_handle,profile_visibility)
  values(v_uid,public.echo_identity_generated_handle(v_uid),'private')
  on conflict(user_id) do nothing;

  select * into v_current
  from public.echo_public_profiles
  where user_id=v_uid
  for update;

  if v_current.public_handle <> v_handle
     and v_current.public_handle <> public.echo_identity_generated_handle(v_uid)
     and v_current.handle_changed_at is not null
     and v_current.handle_changed_at > now() - interval '30 days' then
    raise exception 'handle_change_cooldown' using errcode='42501';
  end if;

  begin
    update public.echo_public_profiles
    set public_handle=v_handle,
        bio=v_bio,
        profile_accent=p_accent,
        profile_visibility=p_visibility,
        allow_messages=coalesce(p_allow_messages,false),
        profile_completed_at=coalesce(profile_completed_at,now()),
        handle_changed_at=case when public_handle is distinct from v_handle then now() else handle_changed_at end
    where user_id=v_uid;
  exception when unique_violation then
    raise exception 'public_handle_unavailable' using errcode='23505';
  end;

  update public.profiles set display_name=v_display where id=v_uid;

  return jsonb_build_object(
    'user_id',v_uid,'public_handle',v_handle,'display_name',v_display,
    'bio',v_bio,'profile_accent',p_accent,'profile_visibility',p_visibility,
    'allow_messages',coalesce(p_allow_messages,false)
  );
end;
$$;
revoke all on function public.echo_set_my_public_identity_v1(text,text,text,text,text,boolean) from public, anon;
grant execute on function public.echo_set_my_public_identity_v1(text,text,text,text,text,boolean) to authenticated;

-- ---------------------------------------------------------------------------
-- 8. Auditoria de badges e Founder.
-- ---------------------------------------------------------------------------
create or replace function public.echo_identity_audit_authority_change()
returns trigger
language plpgsql
security definer
set search_path=''
as $$
declare
  v_target uuid;
  v_value text;
  v_action text;
  v_reason text;
begin
  if tg_table_name='echo_identity_badges' then
    v_target := coalesce(new.user_id,old.user_id);
    v_value := coalesce(new.badge_type,old.badge_type);
    v_reason := coalesce(new.grant_reason,old.grant_reason);
    v_action := case
      when tg_op='INSERT' then 'grant'
      when tg_op='DELETE' then 'revoke'
      when old.active=false and new.active=true then 'grant'
      when old.active=true and new.active=false then 'revoke'
      else 'replace'
    end;
    insert into public.echo_identity_authority_audit(
      target_user_id,authority_kind,authority_value,action,actor_user_id,actor_role,reason,context
    ) values (
      v_target,'badge',v_value,v_action,auth.uid(),auth.role(),v_reason,
      jsonb_build_object('operation',tg_op)
    );
  else
    v_target := coalesce(new.user_id,old.user_id);
    v_value := 'founder';
    v_reason := coalesce(new.assignment_reason,old.assignment_reason);
    v_action := case when tg_op='INSERT' then 'grant' when tg_op='DELETE' then 'revoke' else 'transfer' end;
    insert into public.echo_identity_authority_audit(
      target_user_id,authority_kind,authority_value,action,actor_user_id,actor_role,reason,context
    ) values (
      v_target,'founder',v_value,v_action,auth.uid(),auth.role(),v_reason,
      jsonb_build_object('operation',tg_op,'previous_user_id',case when tg_op='UPDATE' then old.user_id else null end)
    );
  end if;
  return null;
end;
$$;
revoke all on function public.echo_identity_audit_authority_change() from public, anon, authenticated, service_role;

drop trigger if exists echo_identity_badges_audit on public.echo_identity_badges;
create trigger echo_identity_badges_audit
after insert or update or delete on public.echo_identity_badges
for each row execute function public.echo_identity_audit_authority_change();

drop trigger if exists echo_founder_authority_audit on public.echo_founder_authority;
create trigger echo_founder_authority_audit
after insert or update or delete on public.echo_founder_authority
for each row execute function public.echo_identity_audit_authority_change();

-- Badges institucionais: Admin AAL2 pode conceder somente os tipos não técnicos.
create or replace function public.admin_set_identity_badge_v1(
  p_user_id uuid,
  p_badge_type text,
  p_active boolean,
  p_reason text default null,
  p_reference_url text default null
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
begin
  if not public.echo_is_admin() then
    raise exception 'admin_aal2_required' using errcode='42501';
  end if;
  if p_badge_type not in ('creator','partner','moderator','developer') then
    raise exception 'institutional_badge_not_allowed' using errcode='22023';
  end if;
  if not exists (select 1 from public.profiles p where p.id=p_user_id and coalesce(p.is_blocked,false)=false) then
    raise exception 'target_profile_unavailable' using errcode='22023';
  end if;
  if p_reference_url is not null and p_reference_url !~ '^https://' then
    raise exception 'reference_url_must_be_https' using errcode='22023';
  end if;

  insert into public.echo_identity_badges(
    user_id,badge_type,active,reference_url,grant_reason,granted_by,granted_at,revoked_by,revoked_at
  ) values (
    p_user_id,p_badge_type,coalesce(p_active,false),p_reference_url,nullif(btrim(coalesce(p_reason,'')),''),
    case when p_active then auth.uid() else null end,now(),
    case when not p_active then auth.uid() else null end,case when not p_active then now() else null end
  )
  on conflict(user_id,badge_type) do update set
    active=excluded.active,
    reference_url=coalesce(excluded.reference_url,public.echo_identity_badges.reference_url),
    grant_reason=coalesce(excluded.grant_reason,public.echo_identity_badges.grant_reason),
    granted_by=case when excluded.active then auth.uid() else public.echo_identity_badges.granted_by end,
    granted_at=case when excluded.active then now() else public.echo_identity_badges.granted_at end,
    revoked_by=case when excluded.active then null else auth.uid() end,
    revoked_at=case when excluded.active then null else now() end;

  return jsonb_build_object('user_id',p_user_id,'badge_type',p_badge_type,'active',coalesce(p_active,false));
end;
$$;
revoke all on function public.admin_set_identity_badge_v1(uuid,text,boolean,text,text) from public, anon;
grant execute on function public.admin_set_identity_badge_v1(uuid,text,boolean,text,text) to authenticated;

-- FOUNDER: nenhum Admin normal recebe EXECUTE. Somente service_role pode transferir.
create or replace function public.echo_set_founder_server_only(p_user_id uuid,p_reason text default null)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
begin
  if coalesce(auth.role(),'') <> 'service_role' then
    raise exception 'service_role_required' using errcode='42501';
  end if;
  if not exists (
    select 1 from public.profiles p
    where p.id=p_user_id
      and coalesce(p.is_blocked,false)=false
      and (lower(coalesce(p.role,''))='admin' or coalesce(p.is_admin,false)=true)
  ) then
    raise exception 'founder_must_be_active_admin' using errcode='22023';
  end if;

  insert into public.echo_founder_authority(singleton,user_id,assigned_at,assigned_by,assignment_reason)
  values(true,p_user_id,now(),auth.uid(),nullif(btrim(coalesce(p_reason,'')),''))
  on conflict(singleton) do update set
    user_id=excluded.user_id,assigned_at=now(),assigned_by=auth.uid(),assignment_reason=excluded.assignment_reason,updated_at=now();

  return jsonb_build_object('user_id',p_user_id,'authority','founder');
end;
$$;
revoke all on function public.echo_set_founder_server_only(uuid,text) from public, anon, authenticated;
grant execute on function public.echo_set_founder_server_only(uuid,text) to service_role;

-- ---------------------------------------------------------------------------
-- 9. Creator claims.
-- ---------------------------------------------------------------------------
create or replace function public.echo_request_creator_verification_v1(p_platform text,p_channel_url text)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_uid uuid := auth.uid();
  v_code text;
  v_hash text;
  v_id uuid;
begin
  if v_uid is null then raise exception 'authentication_required' using errcode='42501'; end if;
  if not exists (select 1 from public.profiles p where p.id=v_uid and coalesce(p.is_blocked,false)=false) then
    raise exception 'active_profile_required' using errcode='42501';
  end if;
  if p_platform not in ('youtube','twitch','tiktok','instagram','facebook','x','other') then
    raise exception 'unsupported_creator_platform' using errcode='22023';
  end if;
  if p_channel_url is null or p_channel_url !~ '^https://' or char_length(p_channel_url)>1000 then
    raise exception 'invalid_creator_channel_url' using errcode='22023';
  end if;
  if (select count(*) from public.echo_creator_claims c where c.user_id=v_uid and c.requested_at>now()-interval '24 hours') >= 5 then
    raise exception 'creator_claim_rate_limited' using errcode='42501';
  end if;
  if (select count(*) from public.echo_creator_claims c where c.user_id=v_uid and c.status='pending' and c.expires_at>now()) >= 3 then
    raise exception 'too_many_pending_creator_claims' using errcode='42501';
  end if;

  v_code := 'ECHO-' || upper(substr(encode(extensions.gen_random_bytes(8),'hex'),1,10));
  v_hash := encode(extensions.digest(convert_to(v_code,'UTF8'),'sha256'),'hex');
  insert into public.echo_creator_claims(user_id,platform,channel_url,proof_code,proof_code_hash,expires_at)
  values(v_uid,p_platform,p_channel_url,v_code,v_hash,now()+interval '7 days')
  returning id into v_id;
  return jsonb_build_object('claim_id',v_id,'proof_code',v_code,'expires_at',now()+interval '7 days');
end;
$$;
revoke all on function public.echo_request_creator_verification_v1(text,text) from public, anon;
grant execute on function public.echo_request_creator_verification_v1(text,text) to authenticated;

create or replace function public.admin_review_creator_claim_v1(p_claim_id uuid,p_decision text,p_note text default null)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_claim public.echo_creator_claims%rowtype;
begin
  if not public.echo_is_admin() then raise exception 'admin_aal2_required' using errcode='42501'; end if;
  if p_decision not in ('verified','rejected') then raise exception 'invalid_creator_claim_decision' using errcode='22023'; end if;
  select * into v_claim from public.echo_creator_claims where id=p_claim_id for update;
  if not found then raise exception 'creator_claim_not_found' using errcode='22023'; end if;
  if v_claim.status <> 'pending' then raise exception 'creator_claim_already_reviewed' using errcode='22023'; end if;
  if p_decision='verified' and v_claim.expires_at <= now() then
    update public.echo_creator_claims set status='expired',reviewed_by=auth.uid(),reviewed_at=now(),review_note='Desafio expirado antes da verificação.' where id=p_claim_id;
    raise exception 'creator_claim_expired' using errcode='22023';
  end if;

  update public.echo_creator_claims
  set status=p_decision,reviewed_by=auth.uid(),reviewed_at=now(),review_note=nullif(btrim(coalesce(p_note,'')),'')
  where id=p_claim_id;

  if p_decision='verified' then
    perform public.admin_set_identity_badge_v1(v_claim.user_id,'creator',true,'Canal verificado por desafio EchoArena',v_claim.channel_url);
  end if;
  return jsonb_build_object('claim_id',p_claim_id,'status',p_decision,'user_id',v_claim.user_id);
end;
$$;
revoke all on function public.admin_review_creator_claim_v1(uuid,text,text) from public, anon;
grant execute on function public.admin_review_creator_claim_v1(uuid,text,text) to authenticated;

