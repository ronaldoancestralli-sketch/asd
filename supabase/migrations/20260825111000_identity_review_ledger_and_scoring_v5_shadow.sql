-- ---------------------------------------------------------------------------
-- 3. Revisão primária V5: correções exigem motivo e são limitadas por janela.
-- A função grava o estado; o trigger acima cria a trilha encadeada.
-- ---------------------------------------------------------------------------
create or replace function public.admin_review_research_contribution_v1(
  p_contribution_id uuid,
  p_status text,
  p_note text default null,
  p_first_discovery boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_row public.echo_research_contributions%rowtype;
  v_policy public.echo_research_guardrail_policy%rowtype;
  v_event_id bigint;
  v_revision integer;
  v_confirmation_state text;
begin
  if not public.echo_is_admin() then raise exception 'admin_aal2_required' using errcode='42501'; end if;
  if p_status not in ('corroborated','verified','rejected','contested','superseded') then
    raise exception 'invalid_research_review_status' using errcode='22023';
  end if;
  if coalesce(p_first_discovery,false) and p_status<>'verified' then
    raise exception 'first_discovery_requires_verified' using errcode='22023';
  end if;
  if p_note is not null and char_length(p_note)>1600 then
    raise exception 'research_review_note_too_long' using errcode='22023';
  end if;

  select * into v_policy from public.echo_research_guardrail_policy where singleton=true;
  if not found then raise exception 'research_guardrail_policy_missing' using errcode='55000'; end if;

  select * into v_row
  from public.echo_research_contributions
  where id=p_contribution_id
  for update;
  if not found then raise exception 'research_contribution_not_found' using errcode='22023'; end if;

  if v_row.status=p_status
     and v_row.is_first_discovery=coalesce(p_first_discovery,false)
     and v_row.review_confirmation_state<>'disputed' then
    raise exception 'research_review_no_change' using errcode='22023';
  end if;
  if v_row.review_revision>0 and nullif(btrim(coalesce(p_note,'')),'') is null then
    raise exception 'research_rereview_reason_required' using errcode='22023';
  end if;
  if (
    select count(*) from public.echo_research_review_events e
    where e.contribution_id=p_contribution_id
      and e.created_at>now()-(v_policy.submission_window_minutes*interval '1 minute')
  )>=v_policy.max_review_revisions_per_window then
    raise exception 'research_review_revision_limited' using errcode='42501';
  end if;

  if coalesce(p_first_discovery,false) then
    if v_row.contributor_id=auth.uid() then
      raise exception 'first_discovery_self_review_not_allowed' using errcode='42501';
    end if;
    if v_row.knowledge_fingerprint is null then
      raise exception 'first_discovery_knowledge_missing' using errcode='55000';
    end if;
    perform pg_catalog.pg_advisory_xact_lock(
      pg_catalog.hashtextextended('echo-first-discovery:'||v_row.knowledge_fingerprint,0)
    );
    if exists(
      select 1 from public.echo_research_contributions c
      where c.id<>p_contribution_id
        and c.knowledge_fingerprint=v_row.knowledge_fingerprint
        and c.status='verified'
        and c.is_first_discovery=true
    ) then
      raise exception 'first_discovery_already_claimed' using errcode='23505';
    end if;
  end if;

  update public.echo_research_contributions
  set status=p_status,
      is_first_discovery=coalesce(p_first_discovery,false),
      reviewed_by=auth.uid(),
      reviewed_at=now(),
      review_note=nullif(btrim(coalesce(p_note,'')),'')
  where id=p_contribution_id
  returning current_review_event_id,review_revision,review_confirmation_state
  into v_event_id,v_revision,v_confirmation_state;

  -- Uma nova decisão invalida imediatamente qualquer pontuação derivada do
  -- evento anterior. O novo evento só volta a contar depois do segundo parecer.
  perform public.echo_recompute_community_reputation(v_row.contributor_id);

  return jsonb_build_object(
    'contribution_id',p_contribution_id,
    'status',p_status,
    'contributor_id',v_row.contributor_id,
    'first_discovery',coalesce(p_first_discovery,false),
    'decision_event_id',v_event_id,
    'review_revision',v_revision,
    'confirmation_state',v_confirmation_state,
    'independent_review',v_row.contributor_id is distinct from auth.uid(),
    'reputation_effect','none_until_independent_confirmation'
  );
end;
$$;
revoke all on function public.admin_review_research_contribution_v1(uuid,text,text,boolean) from public,anon;
grant execute on function public.admin_review_research_contribution_v1(uuid,text,text,boolean) to authenticated,service_role;

-- ---------------------------------------------------------------------------
-- 4. Reputação V5: somente o evento atual + confirmação independente contam.
-- Um lock por usuário serializa tier e especialidades concorrentes.
-- ---------------------------------------------------------------------------
create or replace function public.echo_recompute_community_reputation(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path=''
as $$
declare
  v_verified integer;
  v_corroborated integer;
  v_first integer;
  v_decided integer;
  v_accepted integer;
  v_points integer;
  v_rate numeric(5,4);
  v_tier text := 'member';
  v_policy text;
  v_verified_points integer;
  v_corroborated_points integer;
  v_first_bonus integer;
begin
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('echo-community-reputation:'||p_user_id::text,0)
  );

  select m.policy_version,m.verified_points,m.corroborated_points,m.first_discovery_bonus
  into v_policy,v_verified_points,v_corroborated_points,v_first_bonus
  from public.echo_reputation_policy_meta m
  where m.singleton=true;
  if v_policy is null then raise exception 'reputation_policy_missing' using errcode='55000'; end if;

  with eligible as (
    select c.knowledge_fingerprint,c.status,c.is_first_discovery
    from public.echo_research_contributions c
    join public.echo_research_review_events e
      on e.id=c.current_review_event_id
     and e.contribution_id=c.id
     and e.reviewer_id=c.reviewed_by
     and e.new_status=c.status
     and e.new_first_discovery=c.is_first_discovery
    join public.echo_research_review_confirmations f
      on f.decision_event_id=e.id
     and f.contribution_id=c.id
     and f.outcome='confirmed'
    where c.contributor_id=p_user_id
      and c.review_confirmation_state='confirmed'
      and e.reviewer_id is distinct from c.contributor_id
  ), grouped as (
    select
      knowledge_fingerprint,
      bool_or(status='verified') as has_verified,
      bool_or(status='corroborated') as has_corroborated,
      bool_or(status='contested') as has_contested,
      bool_or(status='rejected') as has_rejected,
      bool_or(status='verified' and is_first_discovery=true) as has_first
    from eligible
    group by knowledge_fingerprint
  ), normalized as (
    select
      case
        when has_verified then 'verified'
        when has_corroborated then 'corroborated'
        when has_contested then 'contested'
        when has_rejected then 'rejected'
        else 'neutral'
      end as effective_status,
      has_first
    from grouped
  )
  select
    count(*) filter(where effective_status='verified')::integer,
    count(*) filter(where effective_status='corroborated')::integer,
    count(*) filter(where has_first=true)::integer,
    count(*) filter(where effective_status in ('verified','corroborated','rejected','contested'))::integer
  into v_verified,v_corroborated,v_first,v_decided
  from normalized;

  v_verified:=coalesce(v_verified,0);
  v_corroborated:=coalesce(v_corroborated,0);
  v_first:=coalesce(v_first,0);
  v_decided:=coalesce(v_decided,0);
  v_accepted:=v_verified+v_corroborated;
  v_points:=v_verified*v_verified_points + v_corroborated*v_corroborated_points + v_first*v_first_bonus;
  v_rate:=case when v_decided=0 then 0 else least(1,greatest(0,v_accepted::numeric/v_decided::numeric)) end;

  select r.tier into v_tier
  from public.echo_reputation_tier_rules r
  where r.policy_version=v_policy
    and v_points>=r.min_points
    and v_verified>=r.min_verified
    and v_first>=r.min_first_discoveries
    and v_rate>=r.min_acceptance_rate
  order by r.ordinal desc
  limit 1;
  v_tier:=coalesce(v_tier,'member');

  insert into public.echo_community_reputation(
    user_id,reputation_points,community_tier,verified_count,corroborated_count,first_discoveries,
    acceptance_rate,accepted_count,decided_count,policy_version,updated_at
  ) values(
    p_user_id,v_points,v_tier,v_verified,v_corroborated,v_first,
    v_rate,v_accepted,v_decided,v_policy,now()
  )
  on conflict(user_id) do update set
    reputation_points=excluded.reputation_points,
    community_tier=excluded.community_tier,
    verified_count=excluded.verified_count,
    corroborated_count=excluded.corroborated_count,
    first_discoveries=excluded.first_discoveries,
    acceptance_rate=excluded.acceptance_rate,
    accepted_count=excluded.accepted_count,
    decided_count=excluded.decided_count,
    policy_version=excluded.policy_version,
    updated_at=now();

  delete from public.echo_community_specialty_stats s where s.user_id=p_user_id;

  insert into public.echo_community_specialty_stats(
    user_id,specialty_key,specialty_points,verified_count,corroborated_count,first_discoveries,
    accepted_count,decided_count,acceptance_rate,earned_rank,policy_version,updated_at
  )
  with eligible as (
    select c.contribution_type,c.knowledge_fingerprint,c.status,c.is_first_discovery
    from public.echo_research_contributions c
    join public.echo_research_review_events e
      on e.id=c.current_review_event_id
     and e.contribution_id=c.id
     and e.reviewer_id=c.reviewed_by
     and e.new_status=c.status
     and e.new_first_discovery=c.is_first_discovery
    join public.echo_research_review_confirmations f
      on f.decision_event_id=e.id
     and f.contribution_id=c.id
     and f.outcome='confirmed'
    where c.contributor_id=p_user_id
      and c.review_confirmation_state='confirmed'
      and e.reviewer_id is distinct from c.contributor_id
  ), mapped as (
    select
      case
        when contribution_type in ('hero_skill_level','hero_passive') then 'hero_research'
        when contribution_type='equipment_stat' then 'arsenal'
        when contribution_type='patch_change' then 'patch_hunter'
        when contribution_type='counter_evidence' then 'counter_research'
        else null
      end as specialty_key,
      knowledge_fingerprint,status,is_first_discovery
    from eligible
  ), grouped as (
    select
      specialty_key,knowledge_fingerprint,
      bool_or(status='verified') as has_verified,
      bool_or(status='corroborated') as has_corroborated,
      bool_or(status='contested') as has_contested,
      bool_or(status='rejected') as has_rejected,
      bool_or(status='verified' and is_first_discovery=true) as has_first
    from mapped
    where specialty_key is not null
    group by specialty_key,knowledge_fingerprint
  ), normalized as (
    select
      specialty_key,
      case
        when has_verified then 'verified'
        when has_corroborated then 'corroborated'
        when has_contested then 'contested'
        when has_rejected then 'rejected'
        else 'neutral'
      end as effective_status,
      has_first
    from grouped
  ), aggregated as (
    select
      specialty_key,
      count(*) filter(where effective_status='verified')::integer as verified_count,
      count(*) filter(where effective_status='corroborated')::integer as corroborated_count,
      count(*) filter(where has_first=true)::integer as first_discoveries,
      count(*) filter(where effective_status in ('verified','corroborated','rejected','contested'))::integer as decided_count
    from normalized
    group by specialty_key
  ), scored as (
    select
      a.*,
      (a.verified_count*v_verified_points + a.corroborated_count*v_corroborated_points + a.first_discoveries*v_first_bonus)::integer as specialty_points,
      (a.verified_count+a.corroborated_count)::integer as accepted_count,
      case when a.decided_count=0 then 0::numeric
        else least(1,greatest(0,(a.verified_count+a.corroborated_count)::numeric/a.decided_count::numeric))
      end::numeric(5,4) as acceptance_rate
    from aggregated a
  )
  select
    p_user_id,s.specialty_key,s.specialty_points,s.verified_count,s.corroborated_count,s.first_discoveries,
    s.accepted_count,s.decided_count,s.acceptance_rate,
    coalesce((
      select r.rank_key
      from public.echo_community_specialty_rules r
      where r.policy_version='specialty-v1-shadow'
        and r.specialty_key=s.specialty_key
        and s.specialty_points>=r.min_points
        and s.verified_count>=r.min_verified
        and s.acceptance_rate>=r.min_acceptance_rate
      order by r.ordinal desc
      limit 1
    ),'none'),
    'specialty-v1-shadow',now()
  from scored s;
end;
$$;
revoke all on function public.echo_recompute_community_reputation(uuid) from public,anon,authenticated,service_role;

