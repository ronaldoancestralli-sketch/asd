-- EchoArena — Echo Identity + Echo Scouts V1 em Shadow.
-- Identidade pública, reputação comunitária e autoridade institucional são domínios separados.
-- Destino exclusivo desta migration: Supabase SNV.
-- Nenhum cargo institucional é derivado de cadastro, metadata Auth ou pontos comunitários.

begin;

-- ---------------------------------------------------------------------------
-- 1. Identidade pública: separada da tabela profiles e sem e-mail.
-- ---------------------------------------------------------------------------
create table if not exists public.echo_public_profiles (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  public_handle text not null,
  bio text,
  profile_accent text not null default 'violet'
    check (profile_accent in ('violet','cyan','gold','emerald','rose','steel')),
  profile_visibility text not null default 'private'
    check (profile_visibility in ('public','private')),
  allow_messages boolean not null default false,
  profile_completed_at timestamptz,
  handle_changed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint echo_public_profiles_handle_format check (
    public_handle ~ '^[a-z0-9](?:[a-z0-9._-]{1,22}[a-z0-9])$'
  ),
  constraint echo_public_profiles_bio_length check (bio is null or char_length(bio) <= 240)
);

create unique index if not exists echo_public_profiles_handle_unique_ci
  on public.echo_public_profiles(lower(public_handle));

create or replace function public.echo_identity_generated_handle(p_user_id uuid)
returns text
language sql
immutable
set search_path=''
as $$
  select 'player-' || substr(replace(p_user_id::text, '-', ''), 1, 16);
$$;
revoke all on function public.echo_identity_generated_handle(uuid) from public, anon, authenticated;

create or replace function public.echo_identity_handle_reserved(p_handle text)
returns boolean
language sql
immutable
set search_path=''
as $$
  select lower(coalesce(p_handle,'')) = any(array[
    'admin','administrator','administrador','moderator','moderador','mod','developer','dev',
    'founder','owner','creator','partner','support','suporte','staff','official','oficial',
    'echoarena','echo-arena','echo_arena','zeptolab','bulletecho','bullet-echo'
  ]::text[]);
$$;
revoke all on function public.echo_identity_handle_reserved(text) from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- 2. Reputação comunitária: conquistada, sem qualquer privilégio administrativo.
-- ---------------------------------------------------------------------------
create table if not exists public.echo_community_reputation (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  reputation_points integer not null default 0 check (reputation_points >= 0),
  community_tier text not null default 'member'
    check (community_tier in ('member','echo_scout','tracker','cartographer','analyst','vanguard','arena_legend')),
  verified_count integer not null default 0 check (verified_count >= 0),
  corroborated_count integer not null default 0 check (corroborated_count >= 0),
  first_discoveries integer not null default 0 check (first_discoveries >= 0),
  acceptance_rate numeric(5,4) not null default 0 check (acceptance_rate between 0 and 1),
  updated_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- 3. Autoridade institucional: concedida, nunca conquistada por pontos.
-- ADMIN é derivado da autoridade técnica existente. FOUNDER não é badge.
-- ---------------------------------------------------------------------------
create table if not exists public.echo_identity_authority_audit (
  id bigint generated by default as identity primary key,
  target_user_id uuid references public.profiles(id) on delete set null,
  authority_kind text not null check (authority_kind in ('badge','founder')),
  authority_value text not null,
  action text not null check (action in ('grant','revoke','transfer','replace')),
  actor_user_id uuid references public.profiles(id) on delete set null,
  actor_role text,
  reason text,
  context jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint echo_identity_authority_audit_reason_length check (reason is null or char_length(reason) <= 1000),
  constraint echo_identity_authority_audit_context_size check (octet_length(context::text) <= 16384)
);

create table if not exists public.echo_identity_badges (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  badge_type text not null check (badge_type in ('creator','partner','moderator','developer')),
  active boolean not null default true,
  reference_url text,
  grant_reason text,
  granted_by uuid references public.profiles(id) on delete set null,
  granted_at timestamptz not null default now(),
  revoked_by uuid references public.profiles(id) on delete set null,
  revoked_at timestamptz,
  updated_at timestamptz not null default now(),
  unique(user_id, badge_type),
  constraint echo_identity_badges_reference_https check (reference_url is null or reference_url ~ '^https://'),
  constraint echo_identity_badges_reason_length check (grant_reason is null or char_length(grant_reason) <= 1000)
);

-- FOUNDER é singleton e só pode ser trocado pelo caminho server-only abaixo.
create table if not exists public.echo_founder_authority (
  singleton boolean primary key default true check (singleton = true),
  user_id uuid not null unique references public.profiles(id) on delete restrict,
  assigned_at timestamptz not null default now(),
  assigned_by uuid references public.profiles(id) on delete set null,
  assignment_reason text,
  updated_at timestamptz not null default now(),
  constraint echo_founder_authority_reason_length check (assignment_reason is null or char_length(assignment_reason) <= 1000)
);

-- ---------------------------------------------------------------------------
-- 4. Creator Verification: desafio de posse de canal, nunca autoatribuição.
-- O proof_code não é credencial do EchoArena: é um desafio público temporário.
-- Mesmo assim, também armazenamos o hash para integridade/auditoria.
-- ---------------------------------------------------------------------------
create table if not exists public.echo_creator_claims (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  platform text not null check (platform in ('youtube','twitch','tiktok','instagram','facebook','x','other')),
  channel_url text not null,
  proof_code text not null,
  proof_code_hash text not null,
  status text not null default 'pending'
    check (status in ('pending','verified','rejected','expired')),
  requested_at timestamptz not null default now(),
  expires_at timestamptz not null,
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  review_note text,
  constraint echo_creator_claims_https check (channel_url ~ '^https://'),
  constraint echo_creator_claims_code_format check (proof_code ~ '^ECHO-[A-F0-9]{10}$'),
  constraint echo_creator_claims_hash_format check (proof_code_hash ~ '^[a-f0-9]{64}$'),
  constraint echo_creator_claims_review_note_length check (review_note is null or char_length(review_note) <= 1200)
);

create index if not exists echo_creator_claims_user_idx
  on public.echo_creator_claims(user_id, requested_at desc);
create index if not exists echo_creator_claims_pending_idx
  on public.echo_creator_claims(status, expires_at, requested_at desc);

-- ---------------------------------------------------------------------------
-- 5. Echo Research: contribuição é evidência pendente; nunca verdade automática.
-- ---------------------------------------------------------------------------
create table if not exists public.echo_research_contributions (
  id uuid primary key default gen_random_uuid(),
  contributor_id uuid not null references public.profiles(id) on delete cascade,
  contribution_type text not null check (contribution_type in (
    'hero_skill_level','hero_passive','equipment_stat','patch_change','counter_evidence','other'
  )),
  hero_id uuid references public.heroes(id) on delete set null,
  skill_id uuid references public.hero_skills(id) on delete set null,
  subject_key text not null,
  game_version text,
  payload jsonb not null default '{}'::jsonb,
  evidence_kind text not null default 'text'
    check (evidence_kind in ('screenshot','video','official_link','community_link','text','other')),
  evidence_reference text,
  status text not null default 'pending'
    check (status in ('pending','corroborated','verified','rejected','contested','superseded')),
  is_first_discovery boolean not null default false,
  submitted_at timestamptz not null default now(),
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  review_note text,
  updated_at timestamptz not null default now(),
  constraint echo_research_subject_length check (char_length(btrim(subject_key)) between 1 and 160),
  constraint echo_research_game_version_length check (game_version is null or char_length(game_version) <= 80),
  constraint echo_research_payload_object check (jsonb_typeof(payload) = 'object'),
  constraint echo_research_payload_size check (octet_length(payload::text) <= 16384),
  constraint echo_research_evidence_length check (evidence_reference is null or char_length(evidence_reference) <= 1200),
  constraint echo_research_review_note_length check (review_note is null or char_length(review_note) <= 1600),
  constraint echo_research_first_discovery_verified check (not is_first_discovery or status = 'verified')
);

create index if not exists echo_research_contributor_idx
  on public.echo_research_contributions(contributor_id, submitted_at desc);
create index if not exists echo_research_review_queue_idx
  on public.echo_research_contributions(status, submitted_at asc);
create index if not exists echo_research_subject_idx
  on public.echo_research_contributions(contribution_type, subject_key, game_version);
create unique index if not exists echo_research_first_discovery_unique
  on public.echo_research_contributions(contribution_type, subject_key, coalesce(game_version,''))
  where is_first_discovery = true and status = 'verified';

-- ---------------------------------------------------------------------------
-- 6. Bootstrap seguro para perfis existentes e novos.
-- O handle automático nunca usa e-mail e começa PRIVADO até escolha explícita.
-- ---------------------------------------------------------------------------
insert into public.echo_public_profiles(user_id, public_handle, profile_visibility)
select p.id, public.echo_identity_generated_handle(p.id), 'private'
from public.profiles p
on conflict (user_id) do nothing;

insert into public.echo_community_reputation(user_id)
select p.id from public.profiles p
on conflict (user_id) do nothing;

create or replace function public.echo_identity_bootstrap_profile()
returns trigger
language plpgsql
security definer
set search_path=''
as $$
begin
  insert into public.echo_public_profiles(user_id, public_handle, profile_visibility)
  values (new.id, public.echo_identity_generated_handle(new.id), 'private')
  on conflict (user_id) do nothing;

  insert into public.echo_community_reputation(user_id)
  values (new.id)
  on conflict (user_id) do nothing;
  return new;
end;
$$;
revoke all on function public.echo_identity_bootstrap_profile() from public, anon, authenticated, service_role;

drop trigger if exists profiles_echo_identity_bootstrap on public.profiles;
