    coalesce(new.updated_by,auth.uid()),
    jsonb_build_object(
      'public_identity_enabled',old.public_identity_enabled,
      'signup_handle_enabled',old.signup_handle_enabled,
      'public_profiles_enabled',old.public_profiles_enabled,
      'identity_cards_enabled',old.identity_cards_enabled,
      'creator_verification_enabled',old.creator_verification_enabled,
      'research_submission_enabled',old.research_submission_enabled
